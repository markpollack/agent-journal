#!/usr/bin/env bash
# Regenerates the architecture guide's generated material under docs/architecture/generated/.
#
#   scripts/architecture-docs.sh           the extracted component view (ArchUnit) and the tool-call story, then SVG rendering
#   scripts/architecture-docs.sh --appmap  also records the observed-flow pilot with AppMap and exports its sequence diagram
#   scripts/architecture-docs.sh --docx    also exports the guide and the tool-call story as one Word file (pandoc) under target/
#
# The default part runs two ordinary tests with -Darchitecture.regenerate=true; the normal build (./mvnw verify) fails while the
# committed files differ from what those tests yield. The AppMap part is opt-in and never runs in the normal build: it records
# one existing replay test under the AppMap Java agent, keeps the recording under target/ (never committed: .gitignore), and
# commits only the normalized sequence-diagram text, its rendering and a small manifest with the recording's hash.
# Tool versions are pinned below; Maven resolves the jars, npx the AppMap CLI (network on first use).
set -euo pipefail

ROOT=$(cd "$(dirname "$0")/.." && pwd)
OUT="$ROOT/docs/architecture/generated"
M2="${MAVEN_REPO:-$HOME/.m2/repository}"
PLANTUML_VERSION=1.2026.8
APPMAP_AGENT_VERSION=1.30.2
APPMAP_CLI_VERSION=3.204.0
APPMAP_TEST='CliCaptureTest#codexVersionIsDiscoveredOnceByTheDocumentedCommandAndTheThreadIdBecomesTheSession'
cd "$ROOT"

jar() { # groupPath artifact version
    local f="$M2/$1/$2/$3/$2-$3.jar"
    [ -f "$f" ] || ./mvnw -q dependency:get -Dartifact="$(echo "$1" | tr / .):$2:$3" -Dtransitive=false >&2
    echo "$f"
}

echo "== extracted component view and tool-call story"
./mvnw -q test -pl journal-capture-tck,journal-ocsf-writer -Dtest='ComponentViewTest,ToolCallStoryTest' -Dsurefire.failIfNoSpecifiedTests=false \
    -Djacoco.skip=true -Darchitecture.regenerate=true

if [[ " $* " == *" --appmap "* ]]; then
    echo "== observed flow: AppMap recording of $APPMAP_TEST"
    AGENT=$(jar com/appland appmap-agent "$APPMAP_AGENT_VERSION")
    WORK="$ROOT/target/architecture/appmap"
    rm -rf "${WORK:?}"
    mkdir -p "$WORK"
    ./mvnw -q test -pl journal-capture-tck,journal-ocsf-writer -Dtest="$APPMAP_TEST" -Dsurefire.failIfNoSpecifiedTests=false -Djacoco.skip=true \
        "-DargLine=-javaagent:$AGENT -Dappmap.config.file=$ROOT/scripts/architecture/appmap.yml -Dappmap.output.directory=$WORK"
    REC=$(find "$WORK" -name '*.appmap.json' | head -1)
    (cd "$WORK" && npx -y "@appland/appmap@$APPMAP_CLI_VERSION" sequence-diagram --format plantuml --output-dir "$WORK/sequence" \
        --expand package:io/github/markpollack/journal/ocsf/writer --expand package:io/github/markpollack/journal/tck/ocsf "$REC" >/dev/null)
    UML=$(find "$WORK/sequence" -name '*.sequence.uml' | head -1)
    # Normalization (presentation only, no message changed): drop the exporter's remote, unpinned theme include and the
    # per-call elapsed times, which differ on every run; add provenance comments, a title and a legend.
    {
        echo "@startuml"
        echo "' GENERATED by scripts/architecture-docs.sh --appmap; do not edit. Exported by @appland/appmap $APPMAP_CLI_VERSION sequence-diagram from an"
        echo "' AppMap Java agent $APPMAP_AGENT_VERSION recording of $APPMAP_TEST (scope: scripts/architecture/appmap.yml)."
        echo "' Normalized: remote theme include and per-call elapsed times removed; no message changed. See observed-launch-recording.json."
        echo "skinparam shadowing false"
        echo "skinparam defaultFontName Helvetica"
        echo "title Observed: one launching-capture replay test, writer then independent oracle"
        sed -e '1d' -e '/^!includeurl /d' -e 's/ <color:gray> [0-9.]* ms<\/color>//' -e '/^@enduml/d' "$UML"
        echo "legend bottom left"
        echo "  Observed execution of one replayed test within the recording scope: a stand-in script replays a labelled synthetic"
        echo "  Codex exec stream through CliCapture; not a live CLI run, and not every path the code can take."
        echo "  Each thread is drawn as its own block: the CliCapture\$Pump thread maps the records while the main thread polls awaitEnd."
        echo "  Only the listed entry methods were recorded; private methods, JSON values and the test's own code are not shown."
        echo "endlegend"
        echo "@enduml"
    } > "$OUT/observed-launch-sequence.puml"
    python3 - "$REC" "$ROOT/scripts/architecture/appmap.yml" "$OUT/observed-launch-recording.json" "$APPMAP_TEST" "$APPMAP_AGENT_VERSION" "$APPMAP_CLI_VERSION" <<'EOF'
import hashlib, json, os, sys
rec, cfg, out, test, agent, cli = sys.argv[1:]
data = open(rec, 'rb').read()
d = json.loads(data)
calls = [e for e in d['events'] if e.get('event') == 'call']
manifest = {
    "kind": "agent-journal/appmap-recording-manifest",
    "status": "observed execution of one replayed test within the recording scope; the recording itself is not committed",
    "test": test,
    "test_status": d['metadata'].get('test_status'),
    "recorder": {"agent": "com.appland:appmap-agent:" + agent, "jvm": d['metadata']['language']['version'], "config_sha256": hashlib.sha256(open(cfg, 'rb').read()).hexdigest()},
    "exporter": "@appland/appmap@" + cli + " sequence-diagram --format plantuml --expand package:io/github/markpollack/journal/ocsf/writer --expand package:io/github/markpollack/journal/tck/ocsf",
    "recording": {"sha256": hashlib.sha256(data).hexdigest(), "bytes": len(data), "events": len(d['events']), "calls": len(calls),
                  "threads": len({e['thread_id'] for e in calls})},
    "thread_interleaving": {
        "main_awaitEnd_call_ids": [e['id'] for e in calls if e['defined_class'].endswith('CliCapture$Pump') and e['method_id'] == 'awaitEnd'],
        "pump_map_call_ids": [e['id'] for e in calls if e['defined_class'].endswith('CodexStreamMapper') and e['method_id'] == 'map'],
        "meaning": "AppMap event ids are assigned in recording order across threads; the pump thread's map calls fall between the main thread's awaitEnd polls",
    },
    "varies_between_recordings": "elapsed times, object ids, temporary paths, the number of awaitEnd polls and the read chunks standard output arrives in (scheduling); the calls of one run are fixed in its recording",
}
with open(out, 'w') as f:
    json.dump(manifest, f, indent=1)
    f.write('\n')
EOF
fi

echo "== rendering"
PLANTUML=$(jar net/sourceforge/plantuml plantuml "$PLANTUML_VERSION")
java -Djava.awt.headless=true -jar "$PLANTUML" -tsvg "$OUT"/*.puml
echo "generated: $(cd "$OUT" && ls | tr '\n' ' ')"

if [[ " $* " == *" --docx "* ]]; then
    echo "== Word export"
    DOCX="$ROOT/target/architecture/docx"
    rm -rf "${DOCX:?}"
    mkdir -p "$DOCX/generated"
    cp "$OUT"/*.puml "$DOCX/generated/"
    java -Djava.awt.headless=true -jar "$PLANTUML" -tpng "$DOCX/generated"/*.puml
    # the same maintained Markdown; only the image references point at PNG renders, which Word embeds without an SVG converter
    sed -e 's/\.svg)/.png)/' "$ROOT/docs/architecture/README.md" > "$DOCX/README.md"
    sed -e 's/\.svg)/.png)/' "$OUT/tool-call-story.md" > "$DOCX/generated/tool-call-story.md"
    (cd "$DOCX" && pandoc README.md generated/tool-call-story.md --resource-path=.:generated -o "$ROOT/target/architecture/agent-journal-architecture.docx")
    echo "exported: target/architecture/agent-journal-architecture.docx"
fi
