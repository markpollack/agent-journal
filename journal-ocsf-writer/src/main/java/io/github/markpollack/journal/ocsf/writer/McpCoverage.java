package io.github.markpollack.journal.ocsf.writer;

import java.util.ArrayList;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeMap;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * The generated coverage inventory of the MCP binding ({@code schema/protocol/mcp/COVERAGE.md}): per pinned revision,
 * every official definition with its disposition (a generated object, variant or map, free JSON, a scalar, a scalar
 * union, or an alias of another definition) and its members bound; the definitions one revision has and the other
 * lacks; what the pinned TypeScript marks {@code @deprecated}; and the members that also fill shared Journal fields. It
 * states the model's coverage of the pinned schemas, not what any CLI exposes.
 */
final class McpCoverage {

    private static final Pattern DECLARATION = Pattern.compile("^\\s*export\\s+(?:interface|type)\\s+(\\w+)");
    private static final Pattern MEMBER = Pattern.compile("^\\s*\"?([A-Za-z_$][\\w$./-]*)\"?\\??\\s*:");

    /** Members a CLI projection also writes into shared Journal fields; the typed protocol object keeps them too. */
    static final List<String[]> SHARED = List.of(
            new String[] {"CallToolRequestParams.name", "tool_call.mcp.target_tool_name (when reported or derived with its basis); tool_call.tool_name stays the reported name"},
            new String[] {"CallToolRequestParams.arguments", "tool_call.arguments when the call reports the target's arguments as its own (pointer \"\"); inside a dispatcher's arguments at the target_arguments_pointer"},
            new String[] {"CallToolResult.content", "tool_call.tool_result.data (the model-visible result content as the CLI reports it)"},
            new String[] {"CallToolResult.structuredContent", "tool_call.tool_result.structured_result"},
            new String[] {"CallToolResult.isError", "tool_call.tool_result.errors[] layer 2 Tool result error, only where isError is reported; never inferred from a CLI failure"},
            new String[] {"JSONRPCErrorResponse.error", "tool_call.tool_result.errors[] layer 1 JSON-RPC protocol error, only where a JSON-RPC error is reported"},
            new String[] {"Tool", "session_context.tool_definitions[] (definition_format 1 MCP Tool, input_schema and output_schema as json_schema)"});

    private McpCoverage() {
    }

    /** {@code @deprecated} definitions and members of a pinned schema.ts, as {@code Def} and {@code Def.member}. */
    static Set<String> deprecated(String typescript) {
        Set<String> out = new TreeSet<>();
        String current = null;
        boolean pending = false;
        for (String line : typescript.split("\n")) {
            String t = line.trim();
            Matcher d = DECLARATION.matcher(line);
            boolean declaration = d.find();
            boolean comment = t.startsWith("*") || t.startsWith("/**") || t.startsWith("//");
            if (pending && !comment && !t.isEmpty()) {
                Matcher m = MEMBER.matcher(line);
                if (declaration) {
                    out.add(d.group(1));
                }
                else if (current != null && m.find()) {
                    out.add(current + "." + m.group(1));
                }
                pending = false;
            }
            current = declaration ? d.group(1) : current;
            pending |= line.contains("@deprecated");
        }
        return out;
    }

    /** The markdown inventory. */
    static String markdown(Jv pins, Map<String, Map<String, McpNode>> nodes, Map<String, Jv.Obj> defs, Map<String, Set<String>> deprecated, Map<String, Jv> shapes) {
        StringBuilder md = new StringBuilder("# MCP protocol data model coverage\n\n");
        md.append("Generated by `McpBindingGenerator` from `PINS.json` (").append(pins.member("repository").text()).append(" at `").append(pins.member("commit").text())
                .append("`); do not edit. It states how the canonical model contains each pinned definition, not what any CLI exposes.\n\n");
        md.append("| Revision | Definitions | Generated objects | Variants | Maps | Free JSON | Scalars | Scalar unions | Members bound |\n|---|---|---|---|---|---|---|---|---|\n");
        for (Map.Entry<String, Map<String, McpNode>> r : nodes.entrySet()) {
            md.append(summaryRow(r.getKey(), r.getValue(), defs.get(r.getKey()), shapes));
        }
        md.append(versionDifferences(nodes));
        md.append("\n## Deprecated in the pinned TypeScript\n\n");
        deprecated.forEach((rev, set) -> md.append("- ").append(rev).append(": ").append(set.isEmpty() ? "none marked" : String.join(", ", set)).append('\n'));
        md.append("\n## Members that also fill shared Journal fields\n\n| Protocol member | Shared field |\n|---|---|\n");
        SHARED.forEach(s -> md.append("| `").append(s[0]).append("` | ").append(s[1]).append(" |\n"));
        for (Map.Entry<String, Map<String, McpNode>> r : nodes.entrySet()) {
            md.append(definitionTable(r.getKey(), r.getValue(), defs.get(r.getKey()), deprecated.get(r.getKey())));
        }
        return md.toString();
    }

    private static String summaryRow(String rev, Map<String, McpNode> nodes, Jv.Obj defs, Map<String, Jv> shapes) {
        Map<String, Integer> kinds = new TreeMap<>();
        nodes.values().forEach(n -> kinds.merge(kind(n), 1, Integer::sum));
        int members = 0;
        int bound = 0;
        for (Map.Entry<String, McpNode> n : nodes.entrySet()) {
            if (defs.get(n.getKey()).member("properties") instanceof Jv.Obj p && n.getValue() instanceof McpNode.Ref ref && "object".equals(ref.kind())) {
                members += p.members().size();
                Jv shapeMembers = shapes.get(ref.object()).path("revisions", rev, "members");
                bound += shapeMembers instanceof Jv.Obj sm ? (int) p.members().keySet().stream().filter(sm::has).count() : 0;
            }
        }
        return "| " + rev + " | " + nodes.size() + " | " + kinds.getOrDefault("object", 0) + " | " + kinds.getOrDefault("variant", 0) + " | " + kinds.getOrDefault("map", 0)
                + " | " + kinds.getOrDefault("json", 0) + " | " + kinds.getOrDefault("scalar", 0) + " | " + kinds.getOrDefault("scalar_union", 0) + " | " + bound + " of " + members + " |\n";
    }

    private static String versionDifferences(Map<String, Map<String, McpNode>> nodes) {
        List<String> revs = new ArrayList<>(nodes.keySet());
        StringBuilder md = new StringBuilder("\n## Definitions by revision\n\n");
        for (int i = 0; i + 1 < revs.size(); i++) {
            Set<String> earlier = nodes.get(revs.get(i)).keySet();
            Set<String> later = nodes.get(revs.get(i + 1)).keySet();
            md.append("- Only in ").append(revs.get(i)).append(": ").append(String.join(", ", minus(earlier, later))).append('\n');
            md.append("- New in ").append(revs.get(i + 1)).append(": ").append(String.join(", ", minus(later, earlier))).append('\n');
            Set<String> changed = new TreeSet<>();
            for (String d : earlier) {
                if (later.contains(d) && !kind(nodes.get(revs.get(i)).get(d)).equals(kind(nodes.get(revs.get(i + 1)).get(d)))) {
                    changed.add(d + " (" + kind(nodes.get(revs.get(i)).get(d)) + " to " + kind(nodes.get(revs.get(i + 1)).get(d)) + ")");
                }
            }
            md.append("- Changed kind: ").append(changed.isEmpty() ? "none" : String.join(", ", changed)).append('\n');
        }
        return md.toString();
    }

    private static String definitionTable(String rev, Map<String, McpNode> nodes, Jv.Obj defs, Set<String> deprecated) {
        StringBuilder md = new StringBuilder("\n## ").append(rev).append("\n\n| Definition | Disposition | Members |\n|---|---|---|\n");
        for (Map.Entry<String, McpNode> n : nodes.entrySet()) {
            Jv def = defs.get(n.getKey());
            int members = def.member("properties") instanceof Jv.Obj p ? p.members().size() : 0;
            String disposition = disposition(n.getKey(), n.getValue(), def);
            md.append("| ").append(n.getKey()).append(deprecated.contains(n.getKey()) ? " (deprecated)" : "").append(" | ").append(disposition).append(" | ")
                    .append(members == 0 ? "" : Integer.toString(members)).append(" |\n");
        }
        return md.toString();
    }

    private static String disposition(String name, McpNode node, Jv def) {
        if (McpSchemaModel.alias(def)) {
            return "alias of " + McpSchemaModel.refName(def.member("$ref").text());
        }
        return switch (kind(node)) {
            case "object", "variant" -> kind(node) + " `" + ((McpNode.Ref) node).object() + "`";
            case "map" -> "map of entries `" + ((McpNode.Ref) node).object() + "`";
            case "json" -> "free JSON (json_t, exact)";
            case "scalar_union" -> "scalar union (json_t, exact)";
            default -> "scalar " + ((McpNode.Scalar) node).type() + " (" + name + ")";
        };
    }

    static String kind(McpNode n) {
        if (n instanceof McpNode.Ref r) {
            return r.kind();
        }
        if (n instanceof McpNode.Scalar) {
            return "scalar";
        }
        return n instanceof McpNode.ScalarUnion ? "scalar_union" : "json";
    }

    private static Set<String> minus(Set<String> a, Set<String> b) {
        Set<String> out = new TreeSet<>(a);
        out.removeAll(b);
        return out;
    }
}
